#!/usr/bin/env python3
"""Generate the Python live-client models from the checked-in OpenAPI v2 spec.

The output lives in ``packages/fullmag-py/src/fullmag/client/_generated`` and is
committed.  It contains:

* ``models.py``: ``TypedDict``/alias definitions for the transitive schema
  closure of the operations the client uses (ADR 0068, spec §4.2), plus
  ``REQUIRED_FIELDS`` and ``DISCRIMINATED_UNIONS`` tables used for runtime
  validation of request payloads.
* ``operations.py``: the operation table (method, path, parameters, request
  and response schema names).

Schemas listed in ``OPAQUE_SCHEMAS`` are emitted as ``Dict[str, Any]`` aliases;
the DSL produces those documents through its own canonical converters.

Usage: ``python scripts/generate_python_api_models.py [--check]``.
"""
from __future__ import annotations

import argparse
import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC_RELATIVE = Path("apps/control-room/src/kernel/api/generated/openapi-v2.json")
OUTPUT_RELATIVE = Path("packages/fullmag-py/src/fullmag/client/_generated")

# Operations used by ``fullmag.client``; every entry must exist in the spec.
OPERATION_IDS: tuple[str, ...] = (
    "platform_get_platform_health",
    "sessions_get_sessions",
    "sessions_post_sessions",
    "sessions_get_sessions_current",
    "sessions_get_sessions_current_status",
    "model_get_sessions_current_model_scene",
    "model_put_sessions_current_model_scene",
    "model_patch_sessions_current_model_scene",
    "model_post_sessions_current_model_transactions",
    "model_get_sessions_current_model_script",
    "simulation_get_sessions_current_simulation_commands",
    "simulation_post_sessions_current_simulation_commands",
    "simulation_get_sessions_current_simulation_commands_command_id",
    "simulation_get_sessions_current_simulation_runs_current",
    "simulation_get_sessions_current_simulation_stages_execution",
    "data_get_sessions_current_data_quantities",
    "data_get_sessions_current_data_fields",
    "data_get_sessions_current_data_fields_quantity_id_meta",
    "data_get_sessions_current_data_fields_quantity_id_samples_vector",
    "data_get_sessions_current_data_scalars",
    "data_get_sessions_current_data_tables",
    "data_get_sessions_current_data_tables_table_id_rows",
    "data_get_sessions_current_data_tables_table_id_rows_bin",
    "platform_get_sessions_current_events_ws",
)

# Large documents produced by the DSL's canonical converters, not by hand.
OPAQUE_SCHEMAS: frozenset[str] = frozenset(
    {
        "SceneResource",
        "SceneDocument",
        "ScratchSceneDocumentResource",
        "CapabilityMap",
    }
)

HEADER = '''"""Generated by scripts/generate_python_api_models.py from openapi-v2.json.

Do not edit by hand; run ``python scripts/generate_python_api_models.py``.
"""
'''

PRIMITIVES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
    "null": "None",
}


class Generator:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: dict[str, Any] = spec["components"]["schemas"]
        self.parameters: dict[str, Any] = spec["components"].get("parameters", {})
        # name -> rendered definition (class or alias)
        self.definitions: dict[str, str] = {}
        self.required: dict[str, list[str]] = {}
        self.unions: dict[str, dict[str, Any]] = {}
        self.pending: list[str] = []
        self.visited: set[str] = set()

    # ---- schema closure -------------------------------------------------

    def require_schema(self, name: str) -> str:
        if name not in self.schemas:
            raise SystemExit(f"schema {name!r} referenced but missing from spec")
        if name not in self.visited:
            self.visited.add(name)
            self.pending.append(name)
        return name

    def drain(self) -> None:
        while self.pending:
            name = self.pending.pop()
            if name in OPAQUE_SCHEMAS:
                self.definitions[name] = f"{name} = Dict[str, Any]"
                continue
            self.emit_named(name, self.schemas[name])

    # ---- rendering ------------------------------------------------------

    def emit_named(self, name: str, schema: dict[str, Any]) -> None:
        members = schema.get("oneOf") or schema.get("anyOf")
        if members and not schema.get("properties"):
            self.emit_union(name, members)
            return
        if "allOf" in schema or schema.get("properties") is not None or schema.get("type") == "object":
            properties, required = self.merge_object(schema)
            if properties or "additionalProperties" not in schema:
                self.emit_typed_dict(name, properties, required)
                return
        self.definitions[name] = f"{name} = {self.render(schema, name)}"

    def merge_object(self, schema: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
        properties: dict[str, Any] = {}
        required: list[str] = []
        for part in schema.get("allOf", []):
            part = self.resolve(part)
            sub_properties, sub_required = self.merge_object(part)
            properties.update(sub_properties)
            required.extend(sub_required)
        properties.update(schema.get("properties", {}))
        required.extend(schema.get("required", []))
        return properties, sorted(set(required))

    def resolve(self, schema: dict[str, Any]) -> dict[str, Any]:
        if "$ref" in schema:
            return self.schemas[self.ref_name(schema["$ref"])]
        return schema

    @staticmethod
    def ref_name(ref: str) -> str:
        return ref.rsplit("/", 1)[-1]

    def emit_typed_dict(self, name: str, properties: dict[str, Any], required: list[str]) -> None:
        fields = []
        for key in sorted(properties):
            annotation = self.render(properties[key], f"{name}_{camel(key)}")
            fields.append(f"        {key!r}: {annotation!r},")
        body = "\n".join(fields)
        self.definitions[name] = (
            f"{name} = TypedDict(\n    {name!r},\n    {{\n{body}\n    }},\n    total=False,\n)"
            if fields
            else f"{name} = TypedDict({name!r}, {{}}, total=False)"
        )
        self.required[name] = required

    def emit_union(self, name: str, members: list[dict[str, Any]]) -> None:
        rendered: list[str] = []
        discriminator: dict[str, str] = {}
        for index, member in enumerate(members):
            if "$ref" in member:
                ref = self.require_schema(self.ref_name(member["$ref"]))
                rendered.append(ref)
                kind = self.kind_of(self.schemas[ref])
                if kind is not None:
                    discriminator[kind] = ref
                continue
            if member.get("type") == "null":
                rendered.append("None")
                continue
            if member.get("properties") is not None or "allOf" in member:
                kind = self.kind_of(member)
                variant = f"{name}{camel(kind) if kind else index}"
                properties, required = self.merge_object(member)
                self.emit_typed_dict(variant, properties, required)
                rendered.append(variant)
                if kind is not None:
                    discriminator[kind] = variant
                continue
            rendered.append(self.render(member, f"{name}{index}"))
        unique = list(dict.fromkeys(rendered))
        self.definitions[name] = f"{name} = Union[{', '.join(quote_type(item) for item in unique)}]" if len(unique) > 1 else f"{name} = {unique[0]}"
        if discriminator:
            self.unions[name] = {"field": "kind", "variants": dict(sorted(discriminator.items()))}

    def kind_of(self, schema: dict[str, Any]) -> str | None:
        properties, _ = self.merge_object(schema)
        enum = properties.get("kind", {}).get("enum")
        if isinstance(enum, list) and len(enum) == 1 and isinstance(enum[0], str):
            return enum[0]
        return None

    def render(self, schema: Any, hint: str) -> str:
        if schema is True or schema == {}:
            return "Any"
        if not isinstance(schema, dict):
            return "Any"
        if "$ref" in schema:
            return self.require_schema(self.ref_name(schema["$ref"]))
        if "enum" in schema:
            values = ", ".join(repr(value) for value in schema["enum"])
            return f"Literal[{values}]"
        if "const" in schema:
            return f"Literal[{schema['const']!r}]"
        members = schema.get("oneOf") or schema.get("anyOf")
        if members:
            if any(m.get("properties") is not None or "allOf" in m for m in members if isinstance(m, dict)):
                self.visited.add(hint)
                self.emit_union(hint, members)
                return hint
            return union([self.render(member, f"{hint}{index}") for index, member in enumerate(members)])
        if "allOf" in schema:
            parts = schema["allOf"]
            if len(parts) == 1:
                return self.render(parts[0], hint)
            properties, required = self.merge_object(schema)
            self.emit_typed_dict(hint, properties, required)
            return hint
        kind = schema.get("type")
        if isinstance(kind, list):
            return union([self.render({**schema, "type": item}, hint) for item in kind])
        if kind == "array":
            return f"List[{self.render(schema.get('items', {}), hint + 'Item')}]"
        if kind == "object" or "properties" in schema or "additionalProperties" in schema:
            if schema.get("properties"):
                properties, required = self.merge_object(schema)
                self.emit_typed_dict(hint, properties, required)
                return hint
            extra = schema.get("additionalProperties")
            value = self.render(extra, hint + "Value") if isinstance(extra, dict) else "Any"
            return f"Dict[str, {value}]"
        if kind in PRIMITIVES:
            return PRIMITIVES[kind]
        return "Any"

    # ---- operations -----------------------------------------------------

    def operations(self) -> list[dict[str, Any]]:
        by_id: dict[str, dict[str, Any]] = {}
        for path, item in self.spec["paths"].items():
            for method, operation in item.items():
                if isinstance(operation, dict) and "operationId" in operation:
                    by_id[operation["operationId"]] = {"method": method.upper(), "path": path, "operation": operation}
        rows = []
        for operation_id in OPERATION_IDS:
            if operation_id not in by_id:
                raise SystemExit(f"operation {operation_id!r} missing from spec")
            entry = by_id[operation_id]
            operation = entry["operation"]
            path_params: list[str] = []
            query_params: list[str] = []
            header_params: list[str] = []
            for parameter in operation.get("parameters", []):
                if "$ref" in parameter:
                    parameter = self.parameters[self.ref_name(parameter["$ref"])]
                bucket = {"path": path_params, "query": query_params, "header": header_params}.get(parameter.get("in"))
                if bucket is not None:
                    bucket.append(parameter["name"])
            request_schema = None
            for media in operation.get("requestBody", {}).get("content", {}).values():
                ref = media.get("schema", {}).get("$ref")
                if ref:
                    request_schema = self.require_schema(self.ref_name(ref))
            responses: dict[str, list[tuple[str, str | None]]] = {}
            for status, response in sorted(operation.get("responses", {}).items()):
                media_rows = []
                for media_type, media in sorted(response.get("content", {}).items()):
                    ref = (media.get("schema") or {}).get("$ref")
                    name = self.require_schema(self.ref_name(ref)) if ref else None
                    media_rows.append((media_type, name))
                responses[status] = media_rows
            rows.append(
                {
                    "operation_id": operation_id,
                    "method": entry["method"],
                    "path": entry["path"],
                    "path_params": tuple(path_params),
                    "query_params": tuple(sorted(query_params)),
                    "header_params": tuple(sorted(header_params)),
                    "request_schema": request_schema,
                    "responses": responses,
                }
            )
        return rows


def camel(text: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", text) if part)


def quote_type(text: str) -> str:
    return text if text in {"None", "Any", "str", "int", "float", "bool"} else repr(text)


def union(items: list[str]) -> str:
    unique = list(dict.fromkeys(items))
    if len(unique) == 1:
        return unique[0]
    if "None" in unique and len(unique) == 2:
        other = next(item for item in unique if item != "None")
        return f"Optional[{other}]"
    return f"Union[{', '.join(unique)}]"


def render_models(generator: Generator) -> str:
    lines = [
        HEADER,
        "from __future__ import annotations",
        "",
        "from typing import Any, Dict, List, Literal, Optional, TypedDict, Union",
        "",
    ]
    names = sorted(generator.definitions)
    for name in names:
        if keyword.iskeyword(name):
            raise SystemExit(f"schema name {name!r} is a Python keyword")
        lines.append(generator.definitions[name])
        lines.append("")
    lines.append("REQUIRED_FIELDS: Dict[str, frozenset] = {")
    for name in sorted(generator.required):
        fields = ", ".join(repr(field) for field in generator.required[name])
        lines.append(f"    {name!r}: frozenset({{{fields}}})," if fields else f"    {name!r}: frozenset(),")
    lines.append("}")
    lines.append("")
    lines.append("DISCRIMINATED_UNIONS: Dict[str, Dict[str, Any]] = {")
    for name in sorted(generator.unions):
        union_info = generator.unions[name]
        variants = ", ".join(f"{key!r}: {value!r}" for key, value in union_info["variants"].items())
        lines.append(f"    {name!r}: {{'field': {union_info['field']!r}, 'variants': {{{variants}}}}},")
    lines.append("}")
    lines.append("")
    lines.append(f"__all__ = {sorted(names + ['REQUIRED_FIELDS', 'DISCRIMINATED_UNIONS'])!r}")
    return "\n".join(lines) + "\n"


def render_operations(rows: list[dict[str, Any]], spec_version: str) -> str:
    lines = [
        HEADER,
        "from __future__ import annotations",
        "",
        "from typing import Dict, NamedTuple, Optional, Tuple",
        "",
        f"SPEC_VERSION = {spec_version!r}",
        "",
        "",
        "class Operation(NamedTuple):",
        "    operation_id: str",
        "    method: str",
        "    path: str",
        "    path_params: Tuple[str, ...]",
        "    query_params: Tuple[str, ...]",
        "    header_params: Tuple[str, ...]",
        "    request_schema: Optional[str]",
        "    responses: Dict[str, Tuple[Tuple[str, Optional[str]], ...]]",
        "",
        "",
        "OPERATIONS: Dict[str, Operation] = {",
    ]
    for row in rows:
        responses = ", ".join(
            f"{status!r}: ({''.join(f'({media!r}, {name!r}), ' for media, name in media_rows)})"
            for status, media_rows in row["responses"].items()
        )
        lines.extend(
            [
                f"    {row['operation_id']!r}: Operation(",
                f"        operation_id={row['operation_id']!r},",
                f"        method={row['method']!r},",
                f"        path={row['path']!r},",
                f"        path_params={row['path_params']!r},",
                f"        query_params={row['query_params']!r},",
                f"        header_params={row['header_params']!r},",
                f"        request_schema={row['request_schema']!r},",
                f"        responses={{{responses}}},",
                "    ),",
            ]
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate(root: Path = ROOT) -> dict[str, str]:
    spec = json.loads((root / SPEC_RELATIVE).read_text(encoding="utf-8"))
    generator = Generator(spec)
    rows = generator.operations()
    generator.drain()
    return {
        "__init__.py": HEADER,
        "models.py": render_models(generator),
        "operations.py": render_operations(rows, str(spec.get("info", {}).get("version", ""))),
    }


def write_outputs(root: Path = ROOT, *, check: bool = False) -> list[str]:
    """Write (or, with ``check``, compare) the generated files; return stale paths."""
    stale = []
    for name, content in generate(root).items():
        target = root / OUTPUT_RELATIVE / name
        current = target.read_bytes().decode("utf-8") if target.exists() else None
        if current == content:
            continue
        if check:
            stale.append((OUTPUT_RELATIVE / name).as_posix())
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content.encode("utf-8"))
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when committed output differs")
    parser.add_argument("--root", type=Path, default=ROOT, help="checkout root (default: this checkout)")
    args = parser.parse_args()
    stale = write_outputs(args.root.resolve(strict=True), check=args.check)
    if stale:
        print("generated Python API models are stale: " + ", ".join(stale), file=sys.stderr)
        print("run: python scripts/generate_python_api_models.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
